/**
 * Scan the apps that depend on @forge/sneat for Boxicons class names (bx-*)
 * and emit a subset of
 * packages/sneat/assets/vendor/fonts/iconify-icons.css containing only those
 * icons (plus the base .bx rule). Falls back to copying the full file if the
 * scan finds nothing or a required icon is missing from the source sheet.
 *
 * Usage: node scripts/build-sneat-icon-subset.mjs
 */
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const appsDir = path.join(root, "apps");
const sourceCss = path.join(
  root,
  "packages",
  "sneat",
  "assets",
  "vendor",
  "fonts",
  "iconify-icons.css",
);
const outCss = path.join(
  root,
  "packages",
  "sneat",
  "assets",
  "vendor",
  "fonts",
  "iconify-icons.subset.css",
);

const ICON_RE = /\bbx-([a-z0-9-]+)\b/g;
const SIZE_UTILS = new Set(["sm", "md", "lg", "xs", "xl", "chevron"]);

function walk(dir, files = []) {
  if (!fs.existsSync(dir)) return files;
  for (const entry of fs.readdirSync(dir, { withFileTypes: true })) {
    const full = path.join(dir, entry.name);
    if (entry.isDirectory()) {
      if (entry.name === "node_modules" || entry.name === ".next" || entry.name === "out") continue;
      walk(full, files);
    } else if (/\.(tsx?|jsx?|css|md)$/i.test(entry.name)) {
      files.push(full);
    }
  }
  return files;
}

function dependsOnSneat(appDir) {
  const manifest = path.join(appDir, "package.json");
  if (!fs.existsSync(manifest)) return false;
  const pkg = JSON.parse(fs.readFileSync(manifest, "utf8"));
  return Boolean(pkg.dependencies?.["@forge/sneat"] || pkg.devDependencies?.["@forge/sneat"]);
}

function collectIcons() {
  const icons = new Set();
  const appRoots = fs.existsSync(appsDir)
    ? fs
        .readdirSync(appsDir)
        .map((name) => path.join(appsDir, name))
        .filter(dependsOnSneat)
        .map((appDir) => path.join(appDir, "src"))
    : [];
  const extra = [
    path.join(root, "packages", "sneat", "src"),
    path.join(root, "packages", "ui", "src"),
  ];
  for (const dir of [...appRoots, ...extra]) {
    for (const file of walk(dir)) {
      const text = fs.readFileSync(file, "utf8");
      for (const match of text.matchAll(ICON_RE)) {
        const name = match[1];
        if (!name || SIZE_UTILS.has(name)) continue;
        icons.add(name);
      }
    }
  }
  return icons;
}

function extractRules(css, icons) {
  const baseMatch = css.match(/\.bx\s*\{[\s\S]*?\n\}/);
  const base = baseMatch ? baseMatch[0] : ".bx { display: inline-block; }";
  const parts = [base, ""];
  const missing = [];
  for (const name of [...icons].sort()) {
    const re = new RegExp(`\\.bx-${name.replace(/-/g, "\\-")}\\s*\\{[\\s\\S]*?\\n\\}`, "m");
    const found = css.match(re);
    if (found) {
      parts.push(found[0], "");
    } else {
      missing.push(name);
    }
  }
  return { css: parts.join("\n"), missing };
}

function main() {
  if (!fs.existsSync(sourceCss)) {
    console.error(`Missing source icon CSS: ${sourceCss}`);
    process.exit(1);
  }
  const full = fs.readFileSync(sourceCss, "utf8");
  const icons = collectIcons();
  if (icons.size === 0) {
    console.warn("No bx icons found in apps; copying full iconify-icons.css as subset.");
    fs.copyFileSync(sourceCss, outCss);
    return;
  }
  const { css, missing } = extractRules(full, icons);
  if (missing.length > 0) {
    console.warn(
      `Icon subset missing ${missing.length} icon(s) from source sheet: ${missing.join(", ")}. Falling back to full CSS.`,
    );
    fs.copyFileSync(sourceCss, outCss);
    return;
  }
  const header = `/* Auto-generated by scripts/build-sneat-icon-subset.mjs — ${icons.size} icons */\n`;
  fs.writeFileSync(outCss, header + css, "utf8");
  const fullSize = fs.statSync(sourceCss).size;
  const subSize = fs.statSync(outCss).size;
  console.log(
    `Wrote ${outCss} (${icons.size} icons, ${subSize} bytes; full was ${fullSize} bytes)`,
  );
}

main();
